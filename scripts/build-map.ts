// Builds lib/map-data.ts: SVG paths for Niger State and its neighbours, for
// the story map. Run once; the output is committed, so the app never fetches
// boundary data at runtime.
//
//   pnpm map:build
//
// Source: Nigerian state boundaries (GRID3, 2022) via geoBoundaries, CC BY 4.0.
// Pinned to a release commit so the output is reproducible.

import { writeFileSync } from "node:fs";
import path from "node:path";

const SOURCE =
  "https://github.com/wmgeolab/geoBoundaries/raw/9469f09/releaseData/gbOpen/NGA/ADM1/geoBoundaries-NGA-ADM1_simplified.geojson";
const OUT = path.join(process.cwd(), "lib", "map-data.ts");

const WIDTH = 1000; // viewBox width; height follows the state's shape
const MARGIN_DEG = 0.3; // show a little of the neighbouring states
const TOLERANCE = 1.2; // simplification tolerance, in viewBox units

type Point = [number, number];
type Feature = {
  properties: { shapeName: string };
  geometry: { type: "Polygon" | "MultiPolygon"; coordinates: number[][][] | number[][][][] };
};

function outerRings(f: Feature): Point[][] {
  const polys =
    f.geometry.type === "Polygon"
      ? [f.geometry.coordinates as number[][][]]
      : (f.geometry.coordinates as number[][][][]);
  return polys.map((p) => p[0] as Point[]);
}

/** Douglas-Peucker line simplification. */
function simplify(points: Point[], tolerance: number): Point[] {
  if (points.length < 3) return points;
  const [a, b] = [points[0], points[points.length - 1]];
  let maxDist = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    const dist = Math.abs(dy * px - dx * py + b[0] * a[1] - b[1] * a[0]) / len;
    if (dist > maxDist) [maxDist, index] = [dist, i];
  }
  if (maxDist <= tolerance) return [a, b];
  return [
    ...simplify(points.slice(0, index + 1), tolerance).slice(0, -1),
    ...simplify(points.slice(index), tolerance),
  ];
}

/**
 * Closed rings start and end on the same point, which gives Douglas-Peucker a
 * zero-length baseline. Split at the point farthest from the start instead.
 */
function simplifyRing(ring: Point[], tolerance: number): Point[] {
  const [x0, y0] = ring[0];
  let far = 0;
  ring.forEach(([x, y], i) => {
    if (Math.hypot(x - x0, y - y0) > Math.hypot(ring[far][0] - x0, ring[far][1] - y0)) far = i;
  });
  return [
    ...simplify(ring.slice(0, far + 1), tolerance).slice(0, -1),
    ...simplify(ring.slice(far), tolerance),
  ];
}

function toPath(points: Point[]): string {
  return (
    points.map(([x, y], i) => `${i === 0 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`).join("") + "Z"
  );
}

async function main() {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`Download failed: ${res.status}`);
  const { features } = (await res.json()) as { features: Feature[] };

  const niger = features.find((f) => /^niger$/i.test(f.properties.shapeName));
  if (!niger) throw new Error("Niger State not found in source data");

  // View: Niger State's bounding box plus a margin.
  const nigerPts = outerRings(niger).flat();
  const minLon = Math.min(...nigerPts.map((p) => p[0])) - MARGIN_DEG;
  const maxLon = Math.max(...nigerPts.map((p) => p[0])) + MARGIN_DEG;
  const minLat = Math.min(...nigerPts.map((p) => p[1])) - MARGIN_DEG;
  const maxLat = Math.max(...nigerPts.map((p) => p[1])) + MARGIN_DEG;

  // Equirectangular projection, corrected for latitude so the shape isn't
  // stretched. Accurate enough for a state this size.
  const cosLat = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
  const scale = WIDTH / ((maxLon - minLon) * cosLat);
  const height = Math.round((maxLat - minLat) * scale);
  const project = ([lon, lat]: Point): Point => [(lon - minLon) * cosLat * scale, (maxLat - lat) * scale];

  const inView = (ring: Point[]) =>
    ring.some(([lon, lat]) => lon >= minLon && lon <= maxLon && lat >= minLat && lat <= maxLat);

  const pathFor = (f: Feature) =>
    outerRings(f)
      .filter(inView)
      .map((ring) => toPath(simplifyRing(ring.map(project), TOLERANCE)))
      .join("");

  const neighbours = features
    .filter((f) => f !== niger && outerRings(f).some(inView))
    .map((f) => ({ name: f.properties.shapeName, d: pathFor(f) }))
    .sort((a, b) => a.name.localeCompare(b.name));

  const file = `// Generated by scripts/build-map.ts. Do not edit by hand; run \`pnpm map:build\`.
// Boundaries: GRID3 Nigeria state boundaries (2022) via geoBoundaries, CC BY 4.0.

export const MAP_VIEWBOX = { width: ${WIDTH}, height: ${height} } as const;

/** Equirectangular projection used for the paths below; see projectToMap(). */
export const MAP_PROJECTION = {
  minLon: ${minLon.toFixed(5)},
  maxLat: ${maxLat.toFixed(5)},
  cosLat: ${cosLat.toFixed(6)},
  scale: ${scale.toFixed(4)},
} as const;

export const NIGER_STATE_PATH =
  "${pathFor(niger)}";

export const NEIGHBOUR_PATHS: readonly { name: string; d: string }[] = ${JSON.stringify(neighbours, null, 2)};
`;
  writeFileSync(OUT, file);
  const kb = (Buffer.byteLength(file) / 1024).toFixed(1);
  console.log(`Wrote lib/map-data.ts (${kb} KB): viewBox ${WIDTH}x${height}, ${neighbours.length} neighbours`);
  console.log(`Neighbours: ${neighbours.map((n) => n.name).join(", ")}`);
}

main();
